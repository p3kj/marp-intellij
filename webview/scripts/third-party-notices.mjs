// Derives the third-party notices from the esbuild metafile: every npm package that has at least
// one file in the bundle, with its package.json data and the full text of its license and NOTICE files.
// Nothing is hard-coded, so the output follows dependency bumps (Dependabot) automatically.
import { existsSync, readdirSync, readFileSync } from "node:fs"
import path from "node:path"

const LEGAL_FILE = /^(licen[sc]e|copying|notice|unlicense)(\.|-|_|$)/i

/** Finds the package.json that owns `file` (nearest ancestor with a "name"), or null. */
function owningPackageDir(file, root) {
  let dir = path.dirname(path.resolve(root, file))
  while (dir.startsWith(root) && dir !== root) {
    const manifest = path.join(dir, "package.json")
    if (existsSync(manifest) && JSON.parse(readFileSync(manifest, "utf8")).name) return dir
    dir = path.dirname(dir)
  }
  return null
}

function licenseName(pkg) {
  const l = pkg.license ?? pkg.licenses
  if (typeof l === "string") return l
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(" OR ")
  return l?.type ?? "UNKNOWN"
}

function repositoryUrl(pkg) {
  const r = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url
  const url = (r ?? pkg.homepage ?? "").replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://")
  return /^[\w.-]+\/[\w.-]+$/.test(url) ? `https://github.com/${url}` : url
}

/** @returns {{name, version, license, url, legalFiles: {file, text}[]}[]} sorted by name */
export function collectPackages(metafile, root = process.cwd()) {
  const dirs = new Set()
  for (const input of Object.keys(metafile.inputs)) {
    if (!input.split("/").includes("node_modules")) continue
    const dir = owningPackageDir(input, root)
    if (dir) dirs.add(dir)
  }
  return [...dirs]
    .map((dir) => {
      const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"))
      const legalFiles = readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isFile() && LEGAL_FILE.test(e.name))
        .map((e) => e.name)
        .sort()
        .map((file) => ({ file, text: readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n").trim() }))
      return { name: pkg.name, version: pkg.version, license: licenseName(pkg), url: repositoryUrl(pkg), legalFiles }
    })
    .sort((a, b) => a.name.localeCompare(b.name))
}

const RULE = "=".repeat(72)

/** Aligned "package version license" lines, used in NOTICE. */
export function renderSummary(packages) {
  const w1 = Math.max(...packages.map((p) => p.name.length))
  const w2 = Math.max(...packages.map((p) => p.version.length))
  return packages.map((p) => `${p.name.padEnd(w1)}  ${p.version.padEnd(w2)}  ${p.license}`).join("\n")
}

/** The complete THIRD-PARTY-NOTICES.txt shipped next to the bundle. */
export function renderFull(packages) {
  const out = [
    "Third-party software bundled into the Marp Preview webview (marp-preview.js)",
    "",
    "This file is generated by webview/scripts/third-party-notices.mjs from the esbuild",
    "metafile on every webview build. Banner comments kept by esbuild are in",
    "marp-preview.js.LEGAL.txt. Marp Preview itself is MIT licensed, see the NOTICE file.",
    "",
    "Summary",
    "-------",
    renderSummary(packages),
    "",
  ]
  for (const p of packages) {
    out.push(RULE, `${p.name} ${p.version}`, `License: ${p.license}`)
    if (p.url) out.push(`Source: ${p.url}`)
    out.push(RULE, "")
    if (p.legalFiles.length === 0) {
      out.push(`(The package ships no license file; it declares the ${p.license} license in its package.json.)`, "")
    }
    for (const f of p.legalFiles) out.push(`--- ${f.file} ---`, "", f.text, "")
  }
  return out.join("\n")
}
